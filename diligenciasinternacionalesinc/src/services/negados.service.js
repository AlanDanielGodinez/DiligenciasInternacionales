import api from '../lib/api';
export const getNegados=async(params={})=>(await api.get('/negados',{params})).data;
export const getProcesoNegados=async(id)=>(await api.get(`/negados/${id}`)).data;
export const updateProcesoNegados=async(id,payload)=>(await api.patch(`/negados/${id}`,payload)).data;
export const addActividadNegados=async(id,payload)=>(await api.post(`/negados/${id}/actividades`,payload)).data;
export const addNotaNegados=async(id,payload)=>(await api.post(`/negados/${id}/notas`,payload)).data;
export const setPreguntasNegados=async(id,payload)=>(await api.put(`/negados/${id}/preguntas-consulado`,payload)).data;
export const enviarLegalNegados=async(id,payload)=>(await api.post(`/negados/${id}/legal`,payload)).data;
export const cerrarNegados=async(id,payload)=>(await api.post(`/negados/${id}/cerrar`,payload)).data;
export const crearReaplicacionNegados=async(id)=>(await api.post(`/negados/${id}/reaplicacion`)).data;
